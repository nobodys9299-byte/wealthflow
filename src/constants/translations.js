// Build reverse lookup index for English phrases to keys
const TEXT_TO_KEY_MAP = {};
if (TRANSLATIONS.en) {
  Object.keys(TRANSLATIONS.en).forEach((k) => {
    const val = TRANSLATIONS.en[k];
    if (typeof val === 'string') {
      TEXT_TO_KEY_MAP[val.toLowerCase().trim()] = k;
    }
  });
}

export const getTranslation = (langCode, keyOrEnglishText, defaultText = '') => {
  if (!keyOrEnglishText) return defaultText || '';
  const langObj = TRANSLATIONS[langCode] || TRANSLATIONS.en;

  // 1. Exact key match
  if (langObj && langObj[keyOrEnglishText]) {
    return langObj[keyOrEnglishText];
  }

  // 2. English text lookup to key
  const normalizedText = String(keyOrEnglishText).toLowerCase().trim();
  const mappedKey = TEXT_TO_KEY_MAP[normalizedText];
  if (mappedKey && langObj && langObj[mappedKey]) {
    return langObj[mappedKey];
  }

  // 3. Fallback to English translation
  if (TRANSLATIONS.en && TRANSLATIONS.en[keyOrEnglishText]) {
    return TRANSLATIONS.en[keyOrEnglishText];
  }

  return defaultText || keyOrEnglishText;
};
